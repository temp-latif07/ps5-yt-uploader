#!/usr/bin/env python3
"""
Bundle PS5 shortcut assets (param.json and icon0.png) into a C header.
"""

import os
import sys

def bytes_to_c_array(data: bytes, var_name: str) -> str:
    lines = [f"static const uint8_t {var_name}[] = {{"]
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_bytes},")
    lines.append("};")
    lines.append(f"static const size_t {var_name}_size = {len(data)};")
    return "\n".join(lines)

def main():
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    param_path = os.path.join(repo_root, "dist", "shortcut", "PS5YT0001", "sce_sys", "param.json")
    icon_path = os.path.join(repo_root, "dist", "shortcut", "PS5YT0001", "sce_sys", "icon0.png")
    output_path = os.path.join(repo_root, "src", "shortcut_assets.h")

    if not os.path.exists(param_path):
        print(f"Error: {param_path} not found. Run scripts/generate_shortcut.py first.", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(icon_path):
        print(f"Error: {icon_path} not found. Run scripts/generate_shortcut.py first.", file=sys.stderr)
        sys.exit(1)

    with open(param_path, "rb") as f:
        param_data = f.read()
    with open(icon_path, "rb") as f:
        icon_data = f.read()

    header_content = [
        "/* Auto-generated by scripts/bundle_shortcut.py - DO NOT EDIT */",
        "#ifndef SHORTCUT_ASSETS_H",
        "#define SHORTCUT_ASSETS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        bytes_to_c_array(param_data, "g_param_json"),
        "",
        bytes_to_c_array(icon_data, "g_icon0_png"),
        "",
        "#endif /* SHORTCUT_ASSETS_H */",
        ""
    ]

    with open(output_path, "w") as f:
        f.write("\n".join(header_content))

    print(f"Successfully generated {output_path} (param: {len(param_data)} bytes, icon: {len(icon_data)} bytes)")

if __name__ == "__main__":
    main()
