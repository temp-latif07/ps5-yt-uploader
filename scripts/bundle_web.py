#!/usr/bin/env python3
"""
scripts/bundle_web.py
Bundles web dashboard assets (index.html, style.css, app.js) into src/web_assets.h
as embedded C byte arrays.
"""

import os
import sys

def format_c_byte_array(var_name: str, data: bytes) -> str:
    lines = []
    lines.append(f"static const unsigned char {var_name}[] = {{")
    
    # 12 hex bytes per line
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        if i + 12 < len(data):
            lines.append(f"    {hex_bytes},")
        else:
            lines.append(f"    {hex_bytes}, 0x00") # null-terminated for safe string operations
            
    if len(data) == 0:
        lines.append("    0x00")
        
    lines.append("};")
    lines.append(f"static const unsigned int {var_name}_len = {len(data)};\n")
    return "\n".join(lines)

def bundle(repo_root: str) -> None:
    web_dir = os.path.join(repo_root, "web")
    src_dir = os.path.join(repo_root, "src")
    output_file = os.path.join(src_dir, "web_assets.h")

    assets = [
        ("index_html", os.path.join(web_dir, "index.html")),
        ("style_css", os.path.join(web_dir, "style.css")),
        ("app_js", os.path.join(web_dir, "app.js")),
    ]

    for name, path in assets:
        if not os.path.exists(path):
            print(f"Error: Required asset file not found: {path}", file=sys.stderr)
            sys.exit(1)

    header_lines = [
        "/* Auto-generated by scripts/bundle_web.py - DO NOT EDIT MANUALLY */",
        "#ifndef WEB_ASSETS_H",
        "#define WEB_ASSETS_H",
        "",
        "#ifdef __cplusplus",
        "extern \"C\" {",
        "#endif",
        "",
    ]

    total_bytes = 0
    for var_name, path in assets:
        with open(path, "rb") as f:
            content = f.read()
        total_bytes += len(content)
        print(f"Bundling {os.path.basename(path)}: {len(content):,} bytes -> {var_name}")
        header_lines.append(format_c_byte_array(var_name, content))

    header_lines.extend([
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* WEB_ASSETS_H */",
        "",
    ])

    with open(output_file, "w", encoding="utf-8") as f:
        f.write("\n".join(header_lines))

    print(f"Successfully generated {output_file} (Total: {total_bytes:,} bytes embedded)")

if __name__ == "__main__":
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(script_dir)
    bundle(repo_root)
