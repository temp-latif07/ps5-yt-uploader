#!/usr/bin/env python3
"""Generates build/gen/assets.c: embedded web UI files, CA bundle, and tile icon PNG.

    embed.py WEB_DIR CA_BUNDLE OUT_C [TILE_ICON_PNG]
"""
import os
import sys

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json",
}


def c_array(name, data, static=True):
    out = [f"{'static ' if static else ''}const unsigned char {name}[{len(data) + 1}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("    0};")
    return "\n".join(out)


def main():
    if len(sys.argv) not in (4, 5):
        print("usage: embed.py WEB_DIR CA_BUNDLE OUT_C [TILE_ICON_PNG]", file=sys.stderr)
        sys.exit(2)
    web, ca, out = sys.argv[1:4]
    icon_path = sys.argv[4] if len(sys.argv) == 5 else ""
    parts = [
        "// Generated by tools/embed.py. Do not edit.",
        '#include "app.h"',
        "#include <string.h>",
        "",
    ]
    entries = []
    for i, name in enumerate(sorted(os.listdir(web))):
        path = os.path.join(web, name)
        ext = os.path.splitext(name)[1].lower()
        if not os.path.isfile(path) or ext not in TYPES:
            continue
        with open(path, "rb") as f:
            data = f.read()
        parts.append(c_array(f"asset_{i}", data))
        entries.append(f'    {{"{name}", "{TYPES[ext]}", asset_{i}, sizeof asset_{i} - 1}},')
    parts.append("static const asset assets[] = {")
    parts.extend(entries)
    parts.append("};")
    parts.append(
        """
const asset *asset_find(const char *name) {
    for (size_t i = 0; i < sizeof assets / sizeof *assets; i++)
        if (!strcmp(assets[i].name, name)) return &assets[i];
    return NULL;
}
"""
    )
    with open(ca, "rb") as f:
        pem = f.read()
    parts.append(c_array("cacert_pem", pem, static=False))
    parts.append(f"const size_t cacert_pem_len = {len(pem)};")

    if icon_path and os.path.isfile(icon_path):
        with open(icon_path, "rb") as f:
            icon = f.read()
    else:
        icon = b""
    parts.append(c_array("tile_icon_png", icon, static=False))
    parts.append(f"const size_t tile_icon_png_len = {len(icon)};")

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")
    os.replace(tmp, out)


if __name__ == "__main__":
    main()
